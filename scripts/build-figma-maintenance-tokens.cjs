#!/usr/bin/env node
/** Generate source-backed Figma variable/style data without the component builder. */
'use strict';

const fs = require('fs');
const path = require('path');
const {
  buildFigmaFoundations,
} = require('./figma-maintenance-foundations.cjs');
const {
  enrichFigmaMaintenanceAssets,
} = require('./figma-maintenance-assets.cjs');
const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(
  ROOT,
  'examples/figma-plugin/mangrove-maintenance-tokens.json'
);

function buildFigmaMaintenance() {
  const doc = buildFigmaFoundations();
  enrichFigmaMaintenanceAssets({ root: ROOT, ...doc });
  return {
    $comment:
      'GENERATED by scripts/build-figma-maintenance-tokens.cjs from source tokens and guarded style/helper derivations. EXPLORATORY. Variables/styles only.',
    ...doc,
  };
}

function main(argv) {
  const outputIndex = argv.indexOf('--output');
  if (
    outputIndex >= 0 &&
    (!argv[outputIndex + 1] || argv[outputIndex + 1].startsWith('--'))
  )
    throw new Error('--output needs a file path.');
  const output =
    outputIndex >= 0 ? path.resolve(argv[outputIndex + 1]) : OUTPUT;
  const options = argv.filter(
    (_, index) =>
      outputIndex < 0 || (index !== outputIndex && index !== outputIndex + 1)
  );
  if (options.some(option => !['--stdout', '--check'].includes(option)))
    throw new Error('Use --stdout, --check or --output <file>.');
  const doc = buildFigmaMaintenance();
  const json = `${JSON.stringify(doc, null, 2)}\n`;
  if (argv.includes('--stdout')) {
    process.stdout.write(json);
    return;
  }
  if (argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== json)
      throw new Error(
        `Stale or missing output: ${path.relative(ROOT, output)}. Run node scripts/build-figma-maintenance-tokens.cjs${output === OUTPUT ? '' : ` --output ${output}`}.`
      );
    process.stdout.write(
      'build-figma-maintenance-tokens: JSON is current; no files changed\n'
    );
    return;
  }
  fs.mkdirSync(path.dirname(output), { recursive: true });
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== json)
    fs.writeFileSync(output, json);
  process.stdout.write(
    `build-figma-maintenance-tokens: wrote ${path.relative(ROOT, output)} (${doc.variables.length} variables, ${doc.modes.length} modes, ${doc.styles.text.length} text style choices, ${doc.styles.effect.length} effects)\n`
  );
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`build-figma-maintenance-tokens: ${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = { buildFigmaMaintenance, main, OUTPUT };
